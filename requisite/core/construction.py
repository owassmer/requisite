class Quote(Record):
    """A listed market's prices as one read-only response served them (spec §6.5: "Market quotes are stored as prices:
    bid, ask, last, size and timestamp"; I9): dollars per contract, never probabilities."""

    market: str
    yes_bid: Money
    yes_ask: Money
    no_bid: Money
    no_ask: Money
    last: Money
    yes_ask_size: Money
    at: str
    locator: str
    fee: Money | None = None  # the exchange's fee to buy one contract at the ask, by its published schedule; None: unknown


INDICATIVE_QUANTUM = Fraction(1, 10**6)  # an indicative price is rounded up to a millionth of the currency (Price)


def indicative_price(expected_payout: Fraction, loading: Fraction) -> Decimal:
    """An indicative price (Price): the expected discounted payout times (1 + loading), rounded up to a millionth of the
    currency (A06 §6.7: "use expected payout"; spec §8.3: "× (1 + loading)"; the rounding up is ours, so the price never
    understates the formula)."""
    n = math.ceil(Fraction(expected_payout) * (1 + Fraction(loading)) / INDICATIVE_QUANTUM)
    return Decimal(f"{n}e-6")  # read from its digits: exact at any size, no context rounds it


class Price(Record):
    """A candidate's price per unit in one endpoint model (spec §8.3; I9). quoted: the ask of a listed market that settles
    on the same predicate (its IR is the candidate's) plus the exchange's fee to buy at it, recorded apart in the quote
    (spec §6.5: "Fees and spread are recorded separately"; spec §10: "Fees enter every comparison"), the quote kept
    whole. indicative: where no listed market settling on its predicate offers an ask, the expected discounted payout
    under the scenario model's probabilities, from the evaluator's transfers (`expected_payout`, exact), times (1 +
    loading), rounded up to a millionth of the currency, labeled indicative with its convention (A06 §6.7: "use expected
    payout, not one event probability times an undefined payout scalar"). A price is never a probability (I9)."""

    candidate: str
    pricing: Literal["quoted", "indicative"]
    price: Money
    expected_payout: Rational | None
    loading: Rational | None
    convention: str
    quote: Quote | None = None

    @model_validator(mode="after")
    def _source(self) -> Price:
        if (self.pricing == "quoted") != (self.quote is not None):
            raise ValueError("a quoted price keeps its quote, and only it does")
        if self.quote is not None:
            if self.quote.fee is None:
                raise ValueError("a quoted price states the exchange's fee (spec §10: fees enter every comparison)")
            with localcontext(_EXACT):  # the sum exactly: a fee is never rounded away (spec §10)
                total = self.quote.yes_ask + self.quote.fee
            if self.price != total:
                raise ValueError("a quoted price is the ask and the exchange's fee, recorded apart (spec §6.5, §10)")
        if (self.pricing == "indicative") != (self.expected_payout is not None and self.loading is not None):
            raise ValueError("an indicative price states its expected payout and loading, and only it does")
        if self.expected_payout is not None and self.loading is not None:
            if self.price != indicative_price(self.expected_payout, self.loading):
                raise ValueError(f"an indicative price is its expected payout times (1 + loading), rounded up to a "
                                 f"millionth: {indicative_price(self.expected_payout, self.loading)}, not {self.price}")  # fmt: skip
        if self.price < 0:
            raise ValueError("a price is an acquisition cost, not negative")
        return self


class Prices(Record):
    """Each settled candidate's price in one model, and what the listed check found. unpriced: the candidates a listed
    market settling on their predicate offers at an ask whose exchange fee is not known, each with why: a listed quote
    is the price where one exists (spec §8.3) and fees enter every comparison (spec §10), so the ask alone is no
    acquisition cost and an indicative price would stand in for the market's; their cost is not determined, so they
    enter no solve (A04 §4.3: an unresolved parameter blocks point-valued optimization)."""

    model: Model
    prices: Sequence[Price]
    listed: str  # what the listed check found
    unpriced: Mapping[str, str] = Field(default_factory=dict, exclude_if=lambda v: not v)

    @model_validator(mode="after")
    def _apart(self) -> Prices:
        if set(self.unpriced) & {p.candidate for p in self.prices}:
            raise ValueError("a candidate is priced or unpriced, not both")
        return self


class PayoffClass(Record):
    """Candidates the solve cannot tell apart: in every scenario of the model their receipts on the grid and after it are
    the representative's times one factor, and so is their price, the acquisition cost the program subtracts (A06 §6.1:
    A_stj = sum h_jst - c_j, so a column is its receipts and its price together; ours: their columns are then one column
    up to scale, and a solver's choice among them is an arbitrary tie, which A03 forbids reading as a decision). A
    rounding that breaks the price's proportion leaves them apart. members: each candidate and its factor; the
    representative's is 1."""

    representative: str
    members: Sequence[tuple[str, Rational]]

    @model_validator(mode="after")
    def _members(self) -> PayoffClass:
        if (self.representative, Fraction(1)) not in [(m, f) for m, f in self.members]:
            raise ValueError("a class's representative is a member with factor 1")
        if any(f <= 0 for _, f in self.members):
            raise ValueError("a member's factor is positive")
        return self


