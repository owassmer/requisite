class WorstCase(Record):
    """Whether the adverse model's solve is the worst case over every combination of the interval values and event days
    (task 004-1: only where "every candidate's payoff depends on the events and not on the size of the business's own
    loss"), with why it is or is not. Made only where that is shown for every value in between, not only at the two
    endpoints: transfers equal at both ends do not show that they are equal between (definition review, November 2), and
    a candidate settled on when within its window the event happens pays on a day that moves with it. It is shown where
    every event of the scenario model happens on one known day (its window is that day), so no event day lies between
    the models, and every candidate settles in every scenario: each candidate's transfers then depend on which events
    occur alone (it settles on observables the events date, never on the business's loss), and each day's deficit is
    nondecreasing in each loss. Otherwise the two solves are each their endpoint model's, and the adverse one is not
    claimed to be a bound."""

    made: bool
    reason: str


def design_holds(chosen: Sequence[str], value: Fraction, unhedged: Fraction, optimum: Fraction, tolerance: Money) -> bool:
    """Whether the chosen design holds in a re-solve. A design is the chosen portfolio held as one instrument (its
    classes in their chosen proportions), its size chosen by the program within the budget (A06 §6.7: its size may change
    while it holds), and `value` its objective; `unhedged` is the objective of buying nothing, which is the design's
    value where it buys nothing. It holds where it stays an acceptable action: within the decision's tolerance of the
    re-solve's optimum (A03 §3.3: acceptable actions are those with J_a(d) <= inf J_a(d') + epsilon, which "avoids
    treating two differently selected tied optima as a meaningful decision flip"). Buying nothing may be acceptable too;
    that is no flip of the design (definition review, November 2)."""
    tol = Fraction(tolerance)
    return (value if chosen else unhedged) - optimum <= tol


class Repriced(Record):
    """The adverse model re-solved at one loading: what the re-solve buys and its optimum (the recomputed objective of
    its portfolio); and the chosen design at that loading's prices, the chosen portfolio held as one instrument (its
    classes in their chosen proportions) and sized by the same program within the budget (`scale`, in chosen
    portfolios), with its objective; and the objective of buying nothing. Whether the design holds: design_holds."""

    loading: Rational
    structure: Sequence[str]
    optimum: Rational
    scale: Rational
    chosen_portfolio: Rational
    unhedged: Rational
    holds: bool


class Repricing(Record):
    """The chosen design repriced over the loading range before it is said to beat another (spec §8.3; A06 §6.7:
    "Reprice over loading/quote ranges before claiming one design dominates another"): the loadings tested and the
    result at each."""

    chosen: Sequence[str]
    loadings: Sequence[Rational]
    tolerance: Money
    repriced: Sequence[Repriced]

    @model_validator(mode="after")
    def _held(self) -> Repricing:
        if self.tolerance < 0:
            raise ValueError("a tolerance is not negative (A03 §3.3: actions within it of optimal are equally good)")
        tested = [r.loading for r in self.repriced]
        if not self.loadings:
            raise ValueError("a repricing tests at least one loading")
        if len(set(tested)) != len(tested) or set(tested) != set(self.loadings):
            raise ValueError("every loading listed is re-solved once, and only those (A06 §6.7: reprice before claiming)")
        if any(r.holds != design_holds(self.chosen, r.chosen_portfolio, r.unhedged, r.optimum, self.tolerance)
               for r in self.repriced):  # fmt: skip
            raise ValueError("the chosen design holds where it protects materially, within the tolerance of the optimum")
        if any(r.scale < 0 for r in self.repriced):
            raise ValueError("a design's size is not negative")
        return self


