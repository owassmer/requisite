# ---------------------------------------------------------------- observables (spec §8.1)


class ObservableCandidate(Record):
    """A candidate observable for one pending event of a deep case's top k, proposed by an agent (spec §8.1; proposal kind
    "observable", ours: spec §4's kinds name none, and an observable is a contract element, not a proposition). Spec
    §8.1: a candidate "must be determinable from an authoritative source with a known publication schedule and revision
    policy; link to the loss through a stated mechanism; lie beyond the client's material influence; resolve within the
    useful window", and "Each candidate becomes an Observable with a source hierarchy". So `observable` carries its
    sources ranked by authority (the hierarchy), its schedule and its revision policy; `mechanism` states how it links to
    the loss of `exposures` (each "<driver>.<event>", the register's exposures of this event); the judges answer the
    rest (core.ObservableScreen).

    occurs: the value the observable publishes for a day on which the event's adverse state holds; absent: its value for
    a day on which it does not; partial, where the observable has one, its value for a day on which the state holds in
    part (between the two, for a number). Construction's structure templates compare the observable with these, so a
    contract's trigger is written by code, never by the agent (task 004-1: "contract IRs generated by code from library
    structure templates"; spec §8.2 names the structure families and their variants). A date or text observable has no such pair of values, so construction does not take
    one (ours: a date's value is the event's own day, which no fixed comparison states)."""

    event: str
    exposures: Sequence[str]
    observable: Observable
    mechanism: str
    occurs: CmpValue
    absent: CmpValue
    partial: CmpValue | None = None

    @model_validator(mode="after")
    def _values(self) -> ObservableCandidate:
        o = self.observable
        if o.value_type not in ("bool", "category", "number"):
            raise ValueError(f"construction compares an observable with its value while the event holds; a {o.value_type} "
                             "observable has no such fixed value: propose a bool, category or number")  # fmt: skip
        if not o.schedule or not o.schedule.strip():
            raise ValueError("a candidate observable states its publication schedule (spec §8.1)")
        if not self.mechanism.strip():
            raise ValueError("a candidate observable states the mechanism linking it to the loss (spec §8.1)")
        if not self.exposures or any(not x.endswith(f".{self.event}") or x == f".{self.event}" for x in self.exposures):
            raise ValueError(f"a candidate names the exposures of its event it links to, each '<driver>.{self.event}'")
        values = [v for v in (self.occurs, self.absent, self.partial) if v is not None]
        kind = VALUE_KIND[o.value_type]
        if any(v.kind != kind for v in values):
            raise ValueError(f"{o.id} is a {o.value_type}: its values are of kind {kind}")
        keys = [_key(v) for v in values]
        if len(set(keys)) != len(keys):
            raise ValueError("the observable's value while the event holds, otherwise, and in part, are distinct")
        if isinstance(self.occurs, Number):
            assert o.precision is not None  # core.Observable: a number states its precision
            if any(isinstance(v, Number) and v.value % o.precision != 0 for v in values):
                raise ValueError(f"{o.id}'s values are stated at its published precision {o.precision}")
            if isinstance(self.partial, Number) and isinstance(self.absent, Number):
                lo, hi = sorted((self.absent.value, self.occurs.value))
                if not lo < self.partial.value < hi:
                    raise ValueError("a partial value lies between the value while the event holds and otherwise")
        if o.value_type == "bool" and self.partial is not None:
            raise ValueError("a bool observable has no partial value")
        return self


def _key(v: CmpValue) -> tuple[str, object]:
    return (v.kind, Fraction(v.value) if isinstance(v, Number) else v.value)


Hedgeability = Literal["client_can_influence", "source_authoritative", "timely"]
HEDGEABILITY: tuple[Hedgeability, ...] = ("client_can_influence", "source_authoritative", "timely")  # spec §8.1


class HedgeabilityAnswer(Record):
    """One hedgeability question as the judges answered it (spec §8.1): its resolved judgment where two or more
    configurations returned a distribution (None otherwise), the answer the application policy applies ("review" where
    it applies none: A04 §4.1), that answer's status in its question's answer set (None for "review"), and its truth,
    which is the status's (spec §6.3: affirmative TRUE, negative FALSE; I6: not_established, contested and "review" are
    unknown, never coerced)."""

    question: Ref
    resolved: str | None
    applied: str
    status: AnswerStatus | None
    truth: Kleene

    @model_validator(mode="after")
    def _unknown(self) -> HedgeabilityAnswer:
        if (self.applied == "review") != (self.status is None):
            raise ValueError("an applied answer states its status, and only an applied one does")
        if self.resolved is None and self.applied != "review":
            raise ValueError("an answer is applied only from a resolution")
        if self.truth is not (Kleene.UNKNOWN if self.status is None else from_status(self.status)):
            raise ValueError("an answer's truth is its status's: never TRUE or FALSE where it is not established (I6)")
        return self


class ObservableScreen(Record):
    """A candidate observable's hedgeability screen (spec §8.1): client_can_influence, source_authoritative and timely,
    each as judged. It passes where the source is authoritative, the client cannot influence the observable and it is
    timely, each true; an unknown is not a pass (I6: never coerced)."""

    proposal: str
    observable: str
    event: str
    answers: Mapping[str, HedgeabilityAnswer]
    passes: Kleene

    @model_validator(mode="after")
    def _passes(self) -> ObservableScreen:
        if tuple(sorted(self.answers)) != tuple(sorted(HEDGEABILITY)):
            raise ValueError(f"a screen answers exactly {HEDGEABILITY} (spec §8.1)")
        a = self.answers
        expected = conj([a["source_authoritative"].truth, neg(a["client_can_influence"].truth), a["timely"].truth])
        if self.passes is not expected:
            raise ValueError("an observable passes where it is authoritative, beyond the client's influence and timely")
        return self


class ObservableScreening(Record):
    """One run of construction's observable step for a top k (spec §8.1): the requisite run whose top k it served, the
    exposures and events of that top k, the agent runs that proposed candidates, the proposals they led to (active and
    rejected), and a screen of each active one."""

    k: int
    run: str
    exposures: Sequence[str]
    events: Sequence[str]
    agent_runs: Sequence[str]
    proposals: Sequence[str]
    screens: Sequence[ObservableScreen]

    @model_validator(mode="after")
    def _screens(self) -> ObservableScreening:
        if any(s.proposal not in self.proposals for s in self.screens):
            raise ValueError("a screening screens its own proposals")
        if len({s.proposal for s in self.screens}) != len(self.screens):
            raise ValueError("a proposal is screened once")
        return self


# ---------------------------------------------------------------- parameters


class ConstructionParameters(Record):
    """A construction solve's parameters that the definition does not hold elsewhere, each given to the step and recorded
    (task 004-1: "Where it does not, each is a parameter of the step, and its value is recorded in the construction record
    and shown in the report"). The decision spec holds the objective, alpha and the economic tolerance; nothing in the
    definition holds these:
    - k: the register's top k whose exposures construction protects (spec §7.1: "enters the top k of the register");
    - budget: the most premium the portfolio may cost (spec §8: "a budget B");
    - loading and loading_range: the indicative pricing policy's loading, and the range every design is repriced over
      before one is said to beat another (spec §8.3; A06 §6.7);
    - discount_rate: the annual rate of the indicative price's discount convention (simple interest, actual/365, from the
      premium day to each transfer's day: ours, task 004-1 "Its discount convention is yours to choose and record");
    - epsilon: the solver tolerance, absolute on the scaled objective (decisions, "Numbers");
    - eligibility: listed only, or also bilateral (spec §8: "Eligibility (listed only, or also block and bilateral) is a
      parameter, not a judgment"); `listed` names the listed contracts the case held when the step ran (its active
      contract proposals), which is every quote a candidate could take (spec §8.3)."""

    case: str
    decision_spec: Ref
    k: int
    budget: Money
    loading: Rational
    loading_range: tuple[Rational, Rational]
    discount_rate: Rational
    epsilon: Money
    eligibility: Literal["listed", "bilateral"]
    listed: Sequence[str]

    @model_validator(mode="after")
    def _ranges(self) -> ConstructionParameters:
        if self.k < 1:
            raise ValueError("the top k holds at least one exposure")
        if self.budget < 0:
            raise ValueError("a budget is not negative")
        lo, hi = self.loading_range
        if not lo <= self.loading <= hi:
            raise ValueError("the loading lies in its range")
        # A06 §6.7 sets no sign for the loading or the rate (indicative pricing is "an assumption-bearing model"), so a
        # negative one is allowed; what is refused is a price the formula cannot give (ours): 1 + loading not positive
        # prices a payout at nothing or less, and a discount factor that is not positive is refused where it is computed.
        if 1 + lo <= 0:
            raise ValueError("1 + loading is positive over the loading's range: a price of nothing or less is no cost")
        if self.epsilon <= 0:
            raise ValueError("a solver tolerance is positive")
        return self


# ---------------------------------------------------------------- the scenario model (addendum A04 §4.1-4.2)


class Scenario(Record):
    """One joint scenario: which events occur, and its probability as the product of its factors, each an estimate's
    value or, flagged, its complement (an event's not occurring, or a binary branch point's other branch)."""

    id: str
    occurs: Mapping[str, bool]
    probability: Probability
    factors: Sequence[tuple[str, bool]]  # (estimate id, complement)


class ScenarioModel(Record):
    """The scenario model a construction solves under (spec §8.3; A04 §4.1: a future event's probability is a conditional
    probability in a declared real-world scenario model). Its probabilities come only from ProbabilityEstimates over the
    case's events, never from an interval's ends (task 004-1). single_event: one event, its estimate's own meaning.
    independent_events: several events and no committed event tree, joined as independent, an assumption named in
    `assumption`, so the joint's meaning is hypothetical (task 004-1). event_tree: a committed tree's conditional
    branches are the joint (A04 §4.2). Probabilities are exact and sum to exactly one, never normalized (A04 §4.2)."""

    kind: Literal["single_event", "independent_events", "event_tree"]
    events: Sequence[str]
    estimates: Sequence[str]
    tree: Ref | None = None
    meaning: Literal["physical", "hypothetical"]
    assumption: str | None
    scenarios: Sequence[Scenario]

    @model_validator(mode="after")
    def _coherent(self) -> ScenarioModel:
        exact_sum_is_one([s.probability for s in self.scenarios], "a scenario model's probabilities")
        if len({s.id for s in self.scenarios}) != len(self.scenarios):
            raise ValueError("scenario ids are distinct")
        if any(set(s.occurs) != set(self.events) for s in self.scenarios):
            raise ValueError("every scenario says of every event of the model whether it occurs")
        if len({tuple(sorted(s.occurs.items())) for s in self.scenarios}) != len(self.scenarios):
            raise ValueError("no two scenarios assign the events alike")
        if self.kind == "single_event" and len(self.events) != 1:
            raise ValueError("a single-event model has one event")
        if self.kind == "independent_events" and (self.meaning != "hypothetical" or not self.assumption):
            raise ValueError("a joint built under independence is an assumed model: hypothetical, its assumption named")
        if (self.kind == "event_tree") != (self.tree is not None):
            raise ValueError("an event-tree model names its tree, and only it does")
        if any(f not in self.estimates for s in self.scenarios for f, _ in s.factors):
            raise ValueError("a scenario's factors are the model's estimates")
        return self


class EventDay(Record):
    """When an event happens in each endpoint model, as a day of its window's zone: in the adverse model on the earliest
    day it can (its window's first day, or as_of's day, since it is pending), in the favourable model on its window's
    last day (None where the window has no end: it happens after anything the contracts observe). One day per event per
    model, read by settlement and by the business's cash alike (construct.start_adverse, start_favourable: each
    exposure's change starts from this day plus its own lag and payment terms), so each model is one history of the
    events, and only the business model's intervals (share, lag) take their ends (definition review, November 2)."""

    event: str
    tz: str
    earliest: Day
    latest: Day | None

    @model_validator(mode="after")
    def _order(self) -> EventDay:
        if self.latest is not None and self.latest < self.earliest:
            raise ValueError("an event's latest day is not before its earliest")
        return self


# ---------------------------------------------------------------- the business's dated cash (addendum A06 §6.1)


class EndpointLoss(Record):
    """The modeled incremental loss of one endpoint model (task 004-1: "The endpoint models are two: every interval at
    its adverse end (the end that lowers cash), and every interval at its favourable end"; never a midpoint, never masses
    on the ends: A04 §4.1), per scenario (rows in the order of BusinessCash.scenarios) and grid day, positive where cash
    goes out. Each row is one realizable path per exposure (requisite/library/nodes/cash.py)."""

    model: Model
    loss: Sequence[Sequence[Money]]


class BusinessCash(Record):
    """The business on construction's dated grid, computed once through the deep case's own graph (A06 §6.1: "Compute the
    total loss once through the shared business cash-flow model"; requisite/library/nodes/cash.py): the grid's days
    (every day of the planning horizon, in its zone `tz`), the currency of every amount (the entity model's), the day the
    premium is paid, the liquidity at the start
    (B_0: cash on hand and the undrawn credit line, as deep's breach flag counts it), the operating flow of each day
    before the modeled loss (the driver tree's revenue less its costs; the same in every scenario), the reserve floor
    of each day (the decision spec's liquidity floor), and each endpoint model's loss. `convention` states the dating
    and rounding (each day's flows count on that day, rounded to the cent toward less cash, so the computed cash never
    exceeds the exact model's)."""

    tz: str
    currency: str
    grid: Sequence[Day]
    premium_day: Day
    initial: Money
    operating: Sequence[Money]
    reserve: Sequence[Money]
    scenarios: Sequence[str]
    models: Sequence[EndpointLoss]
    convention: str

    @model_validator(mode="after")
    def _shape(self) -> BusinessCash:
        n = len(self.grid)
        if not n or list(self.grid) != sorted(set(self.grid)):
            raise ValueError("the grid's days are increasing")
        if self.premium_day not in self.grid:
            raise ValueError("the premium is paid on a day of the grid (A06 §6.1)")
        if len(self.operating) != n or len(self.reserve) != n:
            raise ValueError("operating flow and reserve are stated for every grid day")
        if tuple(m.model for m in self.models) != MODELS:
            raise ValueError(f"the business has its two endpoint models, in order {MODELS}")
        for m in self.models:
            if len(m.loss) != len(self.scenarios) or any(len(row) != n for row in m.loss):
                raise ValueError("each endpoint model states every scenario's loss on every grid day")
        return self


